// Turns tokens/wds-tokens.json (exported from Figma) into css/tokens.css.
//
// Layers:
//   primitives, dimensions  -> :root (single mode)
//   theme                   -> :root = light, [data-theme="dark"] + prefers-color-scheme = dark
//   typography, breakpoint  -> :root = desktop, @media tablet / mobile overrides
//
// Naming: Figma path -> --wds-<name>. A leading group that only categorises
// (background, components, gradient, spacing, core) is dropped, and a segment
// is dropped when the next one repeats it (text/text-primary -> text-primary).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'tokens/wds-tokens.json'), 'utf8'));
const C = data.collections;

export const BREAKPOINTS = { tablet: 1279, mobile: 767 }; // max-width in px

const DROP_FIRST = new Set(['background', 'components', 'gradient', 'spacing', 'core']);
const DROP_GROUP = new Set(['components', 'gradient']); // also drop the second segment

export function cssName(path) {
  let segs = path.split('/');
  const first = segs[0];
  if (DROP_FIRST.has(first)) segs = segs.slice(DROP_GROUP.has(first) ? 2 : 1);
  segs = segs.filter((s, i) => !(segs[i + 1] && (segs[i + 1] === s || segs[i + 1].startsWith(s + '-'))));
  return '--wds-' + segs.join('-');
}

const UNITLESS = /font-weight|font-stretch|fw-|fst-/;
function cssValue(path, v) {
  if (typeof v === 'string') return path.includes('font-family') ? `"${v.trim()}"` : v;
  if (UNITLESS.test(path)) return path.includes('stretch') ? `${v}%` : String(v);
  return v === 0 ? '0' : `${v}px`;
}

const seen = new Map();
function decl(path, v, ref) {
  const name = cssName(path);
  const prev = seen.get(name);
  if (prev && prev !== path) throw new Error(`Token name collision: ${name} <- ${prev} and ${path}`);
  seen.set(name, path);
  return `  ${name}: ${cssValue(path, v)};${ref ? ` /* ${ref} */` : ''}`;
}

const out = [];
const push = (...l) => out.push(...l);
push('/* GENERATED by scripts/build-tokens.mjs from tokens/wds-tokens.json. Do not edit. */', '');

// Single-mode collections
push('/* Primitives + dimensions */', ':root {');
for (const [p, [v]] of C.primitives.tokens) push(decl(p, v));
for (const [p, [v], ref] of C.dimensions.tokens) push(decl(p, v, ref));
push('}', '');

// Theme: light, dark
const themeBlock = (i) => C.theme.tokens.map(([p, vals, ref]) => decl(p, vals[i], i === 0 ? ref : undefined));
seen.clear(); // theme names are emitted twice on purpose
push('/* Theme: light (default) */', ':root, [data-theme="light"] {', '  color-scheme: light;', ...themeBlock(0), '}', '');
seen.clear();
const dark = themeBlock(1);
push('/* Theme: dark (explicit) */', '[data-theme="dark"] {', '  color-scheme: dark;', ...dark, '}', '');
push('/* Theme: dark (follow OS unless the user picked light) */', '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', '    color-scheme: dark;', ...dark.map((l) => '  ' + l), '  }', '}', '');

// Gradients assembled from their stops
const grads = {};
for (const [p] of C.theme.tokens) {
  if (!p.startsWith('gradient/')) continue;
  const g = p.split('/')[1];
  (grads[g] ||= []).push(`var(${cssName(p)})`);
}
push('/* Gradients (direction is a docs default; check Figma per use) */', ':root {');
for (const [g, stops] of Object.entries(grads)) push(`  --wds-${g}: linear-gradient(135deg, ${stops.join(', ')});`);
push('}', '');

// Responsive collections
const typoVars = (i) => {
  const l = [];
  for (const [name, s] of Object.entries(C.typography.styles)) {
    l.push(`  --wds-${name}-font-size: ${s.size[i]}px;`, `  --wds-${name}-line-height: ${s.lh[i]}px;`, `  --wds-${name}-letter-spacing: ${s.ls[i] === 0 ? '0' : s.ls[i] + 'px'};`);
  }
  return l;
};
const bpVars = (i) => C.breakpoint.tokens.map(([p, vals]) => `  ${cssName(p)}: ${cssValue(p, vals[i])};`);

push('/* Typography + layout: desktop (default) */', ':root {', ...typoVars(0), ...bpVars(0));
for (const [name, s] of Object.entries(C.typography.styles)) push(`  --wds-${name}-font-weight: ${s.weight};`, `  --wds-${name}-font-stretch: ${s.stretch}%;`);
push('}', '');
push(`/* Tablet: ${BREAKPOINTS.mobile + 1}px - ${BREAKPOINTS.tablet}px */`, `@media (max-width: ${BREAKPOINTS.tablet}px) {`, '  :root {', ...typoVars(1).map((l) => '  ' + l), ...bpVars(1).map((l) => '  ' + l), '  }', '}', '');
push(`/* Mobile: up to ${BREAKPOINTS.mobile}px */`, `@media (max-width: ${BREAKPOINTS.mobile}px) {`, '  :root {', ...typoVars(2).map((l) => '  ' + l), ...bpVars(2).map((l) => '  ' + l), '  }', '}', '');

// Text style utility classes, one per Figma text style
push('/* Text styles */');
for (const name of Object.keys(C.typography.styles)) {
  push(`.wds-${name} {`,
    `  font-family: var(--wds-font-family-body), "Inter", system-ui, sans-serif;`,
    `  font-size: var(--wds-${name}-font-size);`,
    `  line-height: var(--wds-${name}-line-height);`,
    `  letter-spacing: var(--wds-${name}-letter-spacing);`,
    `  font-weight: var(--wds-${name}-font-weight);`,
    `  font-stretch: var(--wds-${name}-font-stretch);`,
    name === 'overline' ? '  text-transform: uppercase;\n}' : '}');
}

writeFileSync(join(root, 'css/tokens.css'), out.join('\n') + '\n');
console.log(`tokens.css: ${out.length} lines`);
